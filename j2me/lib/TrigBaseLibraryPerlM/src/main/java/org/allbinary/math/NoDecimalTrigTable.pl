    my ($self, $dx, $dy) = @_;
        my $MAX_VALUE = (int(2147483647));
        my $MIN_VALUE = (int((-2147483648)));
        my $ratio = ($MAX_VALUE - 1);
        if ($dy != 0) {
            my $dxl = ($dx);
            $ratio = int($self->{SCALE} * $dxl / $dy);
            if ($dx <= 0 && $dy < 0) {
                $ratio = $self->{mathUtil}->abslong($ratio);
            }
        }
        if (($dx >= 0 && $dy < 0)) {
            for (my $index = 180; $index > 90; $index--) {
                if ($ratio <= $self->{noDecimalTan}->[$index]) {
                    if ($ratio > $self->{noDecimalTan}->[$index - 1]) {
                        return (((int($index) + 32768) % 65536 - 32768));
                    } elsif ($self->{noDecimalTan}->[$index - 1] == $MAX_VALUE && $ratio > $MIN_VALUE) {
                        return (((int($index) + 32768) % 65536 - 32768));
                    }
                }
            }
        } elsif (($dx < 0 && $dy <= 0)) {
            for (my $index = 270; $index > 180; $index--) {
                if ($ratio < $self->{noDecimalTan}->[$index] && $ratio >= $self->{noDecimalTan}->[$index - 1]) {
                    return (((int($index) + 32768) % 65536 - 32768));
                }
            }
        } elsif (($dx < 0 && $dy > 0)) {
            for (my $index = (scalar(@{$self->{noDecimalTan}}) - 1); $index > 270; $index--) {
